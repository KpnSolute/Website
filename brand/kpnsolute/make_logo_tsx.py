"""Writes apps/hub/src/components/Logo.tsx from layers.json and the lockup. Run from brand/kpnsolute after assets.py:
   python make_logo_tsx.py ../../apps/hub/src/components/Logo.tsx"""
import json, re, sys
L = json.load(open("layers.json"))
rnd = lambda d: re.sub(r"-?\d+\.\d", lambda m: str(round(float(m.group(0)))), d)          # integers: 25% smaller, invisible at logo size
ink, star = rnd(L["ink"]), rnd(L["star"])
svg = open("kpnsolute-lockup.svg").read()
vb = float(re.search(r'viewBox="0 0 ([\d.]+) 128"', svg).group(1))
word = re.sub(r"-?\d+\.\d{2,}", lambda m: f"{float(m.group(0)):.1f}", re.search(r'<path fill="#0A0A0A" d="([^"]+)"/>', svg).group(1))
tr = re.search(r'<g transform="([^"]+)">', svg).group(1)
code = f"""/**
 * The KpnSolute logo: the brand icon (a compass star in woven orbits) beside the wordmark (Josefin Sans, outlined,
 * SIL OFL 1.1). The ink and wordmark take the surrounding text color and the star takes the design system's accent
 * (`--kpn-color-accent`, brand blue), so the logo follows light and dark themes and cannot drift from the UI. On hover
 * or keyboard focus of the logo link the icon turns slowly (site.css); it stays still under prefers-reduced-motion.
 * Generated by brand/kpnsolute/make_logo_tsx.py: change the source there, not these paths.
 */
const ICON_INK = '{ink}';
const ICON_STAR = '{star}';
const WORDMARK = '{word}';

export function Logo({{ height = 36, className }}: {{ height?: number; className?: string }}) {{
  return (
    <svg
      viewBox="0 0 {vb:g} 128"
      height={{height}}
      width={{(height * {vb:g}) / 128}}
      className={{`kpn-logo${{className ? ` ${{className}}` : ''}}`}}
      aria-hidden="true"
      focusable="false"
    >
      <g transform="{tr}">
        <g className="kpn-logo-spin">
          <path fill="currentColor" fillRule="evenodd" d={{ICON_INK}} />
          <path fill="var(--kpn-color-accent, #2f5fe0)" fillRule="evenodd" d={{ICON_STAR}} />
        </g>
      </g>
      <path fill="currentColor" d={{WORDMARK}} />
    </svg>
  );
}}
"""
open(sys.argv[1], "w").write(code); print("wrote", sys.argv[1], len(code))
